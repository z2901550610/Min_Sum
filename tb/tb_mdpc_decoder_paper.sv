  mdpc_decoder_demo dut (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .h_sel(h_sel),
    .x_in(x_in),
    .done(done),
    .success(success),
    .x_out(x_out),
    .iter_count(iter_count)
  );

  initial clk = 1'b0;
  always #5 clk = ~clk;

  task automatic apply_reset;
    begin
      rst_n = 1'b0;
      start = 1'b0;
      x_in = '0;
      repeat (2) @(posedge clk);
      rst_n = 1'b1;
      @(posedge clk);
    end
  endtask

  task automatic run_case(input int case_idx, output int case_success);
    int idx;
    int cycles;
    int out_weight;
    begin
      h_sel = H_SEL_W'(case_idx);
      apply_reset();

      x_in = '0;
      for (idx = 0; idx < ERR_COUNT; idx++) begin
        x_in[ERR_POS[case_idx][idx]] = 1'b1;
      end

      start = 1'b1;
      @(posedge clk);
      start = 1'b0;

      cycles = 0;
      while ((done !== 1'b1) && (cycles < TIMEOUT_CYCLES)) begin
        @(posedge clk);
        cycles++;
      end

      if (done !== 1'b1) begin
        $fatal(1, "paper case %0d timed out after %0d cycles", case_idx, cycles);
      end

      @(posedge clk);
      out_weight = 0;
      for (idx = 0; idx < N; idx++) begin
        out_weight += int'(x_out[idx]);
      end

      case_success = (success === 1'b1) && (out_weight == 0);
      $display("paper case %0d: success=%0d iterations=%0d out_weight=%0d cycles=%0d",
               case_idx, success, iter_count, out_weight, cycles);

      if (success !== 1'b1) begin
        $fatal(1, "paper case %0d did not report success", case_idx);
      end
      if (int'(iter_count) != 4) begin
        $fatal(1, "paper case %0d iterations mismatch: got %0d exp 4", case_idx, iter_count);
      end
      if (out_weight != 0) begin
        $fatal(1, "paper case %0d did not recover zero codeword: output weight=%0d", case_idx, out_weight);
      end
    end
  endtask

  initial begin
    int case_idx;
    int case_success;
    int pass_count;

    h_sel = '0;
    rst_n = 1'b0;
    start = 1'b0;
    x_in = '0;
    pass_count = 0;

    for (case_idx = 0; case_idx < H_NUM; case_idx++) begin
      run_case(case_idx, case_success);
      pass_count += case_success;
    end

    $display("tb_mdpc_decoder_paper PASS: %0d/%0d random H matrices decoded", pass_count, H_NUM);
    $finish;
  end
